-- Atualiza o esquema SC_EVENTOS de uma instalação existente.
-- Executar conectado ao banco da aplicação. Toda alteração é transacional.
\set ON_ERROR_STOP on

BEGIN;
SET LOCAL search_path TO "SC_EVENTOS";
SET LOCAL lock_timeout = '5s';

-- Um vínculo inconsistente interrompe a migração pela validação das FKs.
-- Não inferir papéis nem alterar os eventos dos registros existentes.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_EVENTO_FISCAL_03"
    ON "TB_EVENTO_FISCAL" ("ID_EVENTO", "ID_FISCAL", "IC_COORDENACAO");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_ESTACAO_02" ON "TB_ESTACAO" ("ID_ESTACAO", "ID_EVENTO");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_EMISSAO_06" ON "TB_EMISSAO" ("ID_EMISSAO", "ID_EVENTO");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_INCIDENTE_04" ON "TB_INCIDENTE" ("ID_INCIDENTE", "ID_EVENTO");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_TICKET_04" ON "TB_TICKET" ("ID_TICKET", "ID_EVENTO");

ALTER TABLE "TB_EVENTO"
    ADD COLUMN IF NOT EXISTS "IC_COORDENACAO_RESPONSAVEL" SMALLINT GENERATED ALWAYS AS
        (CASE WHEN "ID_FISCAL_RESPONSAVEL" IS NOT NULL THEN 1::SMALLINT END) STORED;

SELECT $ddl$
    ALTER TABLE "TB_EVENTO" ADD CONSTRAINT "FK_TB_EVENTO_TB_EVENTO_FISCAL_COORDENACAO"
        FOREIGN KEY ("ID_EVENTO", "ID_FISCAL_RESPONSAVEL", "IC_COORDENACAO_RESPONSAVEL")
        REFERENCES "TB_EVENTO_FISCAL" ("ID_EVENTO", "ID_FISCAL", "IC_COORDENACAO")
        DEFERRABLE INITIALLY DEFERRED
$ddl$
WHERE NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = '"TB_EVENTO"'::regclass
      AND conname = 'FK_TB_EVENTO_TB_EVENTO_FISCAL_COORDENACAO'
)
\gexec

ALTER TABLE "TB_EMISSAO"
    DROP CONSTRAINT "FK_TB_EMISSAO_TB_ESTACAO",
    ADD CONSTRAINT "FK_TB_EMISSAO_TB_ESTACAO" FOREIGN KEY ("ID_ESTACAO", "ID_EVENTO")
        REFERENCES "TB_ESTACAO" ("ID_ESTACAO", "ID_EVENTO");
DROP INDEX "IX_TB_EMISSAO_02";
CREATE INDEX "IX_TB_EMISSAO_02" ON "TB_EMISSAO" ("ID_ESTACAO", "ID_EVENTO");

ALTER TABLE "TB_TICKET_EMISSAO" ADD COLUMN IF NOT EXISTS "ID_EVENTO" INTEGER;
UPDATE "TB_TICKET_EMISSAO" AS vinculo
SET "ID_EVENTO" = ticket."ID_EVENTO"
FROM "TB_TICKET" AS ticket
WHERE vinculo."ID_TICKET" = ticket."ID_TICKET" AND vinculo."ID_EVENTO" IS NULL;

ALTER TABLE "TB_TICKET_EMISSAO"
    ALTER COLUMN "ID_EVENTO" SET NOT NULL,
    DROP CONSTRAINT "FK_TB_TICKET_EMISSAO_TB_TICKET",
    DROP CONSTRAINT "FK_TB_TICKET_EMISSAO_TB_EMISSAO",
    ADD CONSTRAINT "FK_TB_TICKET_EMISSAO_TB_TICKET" FOREIGN KEY ("ID_TICKET", "ID_EVENTO")
        REFERENCES "TB_TICKET" ("ID_TICKET", "ID_EVENTO"),
    ADD CONSTRAINT "FK_TB_TICKET_EMISSAO_TB_EMISSAO" FOREIGN KEY ("ID_EMISSAO", "ID_EVENTO")
        REFERENCES "TB_EMISSAO" ("ID_EMISSAO", "ID_EVENTO");
DROP INDEX "IX_TB_TICKET_EMISSAO_02";
CREATE INDEX "IX_TB_TICKET_EMISSAO_02" ON "TB_TICKET_EMISSAO" ("ID_EMISSAO", "ID_EVENTO");
CREATE INDEX IF NOT EXISTS "IX_TB_TICKET_EMISSAO_03" ON "TB_TICKET_EMISSAO" ("ID_TICKET", "ID_EVENTO");

ALTER TABLE "TB_TICKET_INCIDENTE" ADD COLUMN IF NOT EXISTS "ID_EVENTO" INTEGER;
UPDATE "TB_TICKET_INCIDENTE" AS vinculo
SET "ID_EVENTO" = ticket."ID_EVENTO"
FROM "TB_TICKET" AS ticket
WHERE vinculo."ID_TICKET" = ticket."ID_TICKET" AND vinculo."ID_EVENTO" IS NULL;

ALTER TABLE "TB_TICKET_INCIDENTE"
    ALTER COLUMN "ID_EVENTO" SET NOT NULL,
    DROP CONSTRAINT "FK_TB_TICKET_INCIDENTE_TB_TICKET",
    DROP CONSTRAINT "FK_TB_TICKET_INCIDENTE_TB_INCIDENTE",
    ADD CONSTRAINT "FK_TB_TICKET_INCIDENTE_TB_TICKET" FOREIGN KEY ("ID_TICKET", "ID_EVENTO")
        REFERENCES "TB_TICKET" ("ID_TICKET", "ID_EVENTO"),
    ADD CONSTRAINT "FK_TB_TICKET_INCIDENTE_TB_INCIDENTE" FOREIGN KEY ("ID_INCIDENTE", "ID_EVENTO")
        REFERENCES "TB_INCIDENTE" ("ID_INCIDENTE", "ID_EVENTO");
DROP INDEX "IX_TB_TICKET_INCIDENTE_02";
CREATE INDEX "IX_TB_TICKET_INCIDENTE_02" ON "TB_TICKET_INCIDENTE" ("ID_INCIDENTE", "ID_EVENTO");
CREATE INDEX IF NOT EXISTS "IX_TB_TICKET_INCIDENTE_03" ON "TB_TICKET_INCIDENTE" ("ID_TICKET", "ID_EVENTO");

-- Preserva os valores anteriores para consulta histórica sem atribuí-los a eventos.
LOCK TABLE "TB_FISCAL" IN ACCESS EXCLUSIVE MODE;
DO $archive$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_attribute
        WHERE attrelid = '"TB_FISCAL"'::regclass
          AND attname IN ('IC_COORDENACAO', 'IC_ABORDAGEM', 'IC_MONITORACAO')
          AND NOT attisdropped
    ) THEN
        CREATE TABLE "TH_FISCAL_PAPEL_GLOBAL" (
            "ID_FISCAL" INTEGER CONSTRAINT "PK_TH_FISCAL_PAPEL_GLOBAL" PRIMARY KEY,
            "IC_COORDENACAO" SMALLINT NOT NULL,
            "IC_ABORDAGEM" SMALLINT NOT NULL,
            "IC_MONITORACAO" SMALLINT NOT NULL
        );
        COMMENT ON TABLE "TH_FISCAL_PAPEL_GLOBAL" IS
            'Papéis globais legados, preservados na migração para papéis por evento.';
        INSERT INTO "TH_FISCAL_PAPEL_GLOBAL"
        SELECT "ID_FISCAL", "IC_COORDENACAO", "IC_ABORDAGEM", "IC_MONITORACAO"
        FROM "TB_FISCAL";

        ALTER TABLE "TB_FISCAL"
            DROP COLUMN "IC_COORDENACAO",
            DROP COLUMN "IC_ABORDAGEM",
            DROP COLUMN "IC_MONITORACAO";
    END IF;
END
$archive$;

COMMENT ON TABLE "TB_FISCAL" IS 'Cadastro funcional de fiscais e respectivas unidades executantes. NO_FISCAL é dado pessoal identificador.';
COMMENT ON COLUMN "TB_EVENTO"."IC_COORDENACAO_RESPONSAVEL" IS
    'Indicador gerado para exigir coordenação no vínculo do fiscal responsável com o evento.';
COMMENT ON COLUMN "TB_TICKET_EMISSAO"."ID_EVENTO" IS
    'Chave primária - TB_EVENTO. Evento comum ao ticket e à emissão.';
COMMENT ON COLUMN "TB_TICKET_INCIDENTE"."ID_EVENTO" IS
    'Chave primária - TB_EVENTO. Evento comum ao ticket e ao incidente.';

COMMIT;
