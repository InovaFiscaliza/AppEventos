-- Papéis de administração e manutenção do sistema.
\set ON_ERROR_STOP on

BEGIN;
SET LOCAL search_path TO "SC_EVENTOS";
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS "TB_ROLES" (
    "ID_ROLE"  INTEGER NOT NULL,
    "NA_ROLE"  VARCHAR(50) NOT NULL,
    CONSTRAINT "PK_TB_ROLES" PRIMARY KEY ("ID_ROLE")
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TB_ROLES_01" ON "TB_ROLES" ("NA_ROLE");

CREATE TABLE IF NOT EXISTS "TB_FISCAL_ROLE" (
    "ID_FISCAL"      INTEGER NOT NULL,
    "FK_ROLE"        INTEGER NOT NULL,
    "IS_ACTIVE"      BOOLEAN NOT NULL DEFAULT FALSE,
    "DT_CREATED_AT"  TIMESTAMPTZ NOT NULL DEFAULT now(),
    "DT_UPDATED_AT"  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "PK_TB_FISCAL_ROLE" PRIMARY KEY ("ID_FISCAL", "FK_ROLE"),
    CONSTRAINT "FK_TB_FISCAL_ROLE_TB_FISCAL" FOREIGN KEY ("ID_FISCAL") REFERENCES "TB_FISCAL" ("ID_FISCAL"),
    CONSTRAINT "FK_TB_FISCAL_ROLE_TB_ROLES" FOREIGN KEY ("FK_ROLE") REFERENCES "TB_ROLES" ("ID_ROLE")
);
CREATE INDEX IF NOT EXISTS "IX_TB_FISCAL_ROLE_01" ON "TB_FISCAL_ROLE" ("FK_ROLE");

COMMENT ON TABLE "TB_ROLES" IS 'Papéis de administração e manutenção do sistema.';
COMMENT ON TABLE "TB_FISCAL_ROLE" IS 'Papéis de sistema atribuídos a fiscais, independentes da participação em eventos.';
COMMENT ON COLUMN "TB_FISCAL_ROLE"."DT_UPDATED_AT" IS 'Data da última atualização, preenchida pela aplicação ao editar o vínculo.';

INSERT INTO "TB_ROLES" ("ID_ROLE", "NA_ROLE") VALUES
    (1, 'admin'),
    (2, 'developer')
ON CONFLICT ("ID_ROLE") DO NOTHING;

COMMIT;
